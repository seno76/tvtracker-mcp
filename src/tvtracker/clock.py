"""Единственное место, где в программу входит системное время.

Доменные функции принимают «сейчас» аргументом — только так граничные случаи вроде
«серия вышла сегодня, но по UTC ещё не наступила» вообще поддаются проверке. Значит,
системные часы должны читаться ровно в одном месте, на границе слоя MCP.
"""

from __future__ import annotations

from datetime import UTC, datetime


def utcnow() -> datetime:
    """Текущий момент в UTC. `airstamp` от TVmaze тоже в UTC — сравнение корректно."""
    return datetime.now(UTC)
