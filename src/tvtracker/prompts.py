"""Четыре промпта.

Промпт — заготовленная человеком форма разговора, запускается явной командой. Отличие
от инструмента: инструмент решает подзадачу внутри рассуждения модели, промпт задаёт
рассуждению рамку целиком.

Общее правило: **промпты втягивают контекст из ресурсов, а не добывают его
инструментами.** Если шаблон начинается с «сначала вызови такой-то инструмент, чтобы
узнать историю» — примитивы разложены неверно.
"""

from __future__ import annotations

from mcp.server import MCPServer


def register_prompts(server: MCPServer) -> None:
    @server.prompt(title="Что включить сейчас")
    def whats_next(minutes: str, mood: str = "") -> str:
        """Подобрать серию под свободное время из накопившегося."""
        return f"""\
У пользователя свободно {minutes} минут. Настроение: {mood or "не указано"}.

Возьми накопившиеся серии и профиль вкуса из ресурсов tracking://backlog,
tracking://watching и tracking://taste — они уже в контексте, ходить за ними
инструментами не нужно.

Правила:
- предлагай ТОЛЬКО то, что уже вышло и лежит в бэклоге;
- серия должна укладываться в {minutes} минут с запасом 10 %;
- не более трёх вариантов, каждый — одна строка обоснования;
- если ничего не подходит по времени, скажи это прямо и предложи одну
  альтернативу, а не список;
- никаких описаний непросмотренных серий: только название и длительность.

Допустим максимум один вызов watch_next для ранжирования."""

    @server.prompt(title="Что я пропустил")
    def catch_up(since: str = "") -> str:
        """Сводка: что вышло, что впереди и с чего продолжать."""
        period = since or "с последнего просмотра"
        return f"""\
Пользователь не следил за сериалами {period}. Составь сводку из трёх частей,
опираясь на ресурсы tracking://backlog, tracking://schedule и tracking://watching.

1. Что вышло за это время — по сериалам, с числом серий и общим временем.
2. Что выходит в ближайшие две недели.
3. С чего продолжать: ровно один конкретный совет — сериал и номер серии.

Раздел 3 обязателен и не должен быть списком. Если продолжать нечего —
скажи это прямо, не придумывай занятие."""

    @server.prompt(title="Найти по описанию")
    def find_by_vibe(description: str) -> str:
        """Найти сериал, название которого пользователь не помнит."""
        return f"""\
Пользователь описывает сериал, названия которого не помнит: «{description}»

Порядок:
1. Вызови show_search с by="description".
2. Если в выдаче есть явный лидер — назови его и спроси, он ли это.
3. Если кандидатов много и они разнородные — задай ОДИН уточняющий вопрос
   (страна, десятилетие, тон, длина) и повтори поиск с фильтром.
   Значения фильтров бери из catalog://facets, не выдумывай: жанр пишется
   "Science-Fiction", а не "Sci-Fi".
4. Если ничего не найдено — предложи переформулировать описание другими словами
   и объясни, что поиск идёт по тексту описаний: индекс не понимает пересказ смысла,
   ему нужны слова, близкие к оригинальной аннотации.

Помечай сериалы, которые пользователь уже смотрел или бросал."""

    @server.prompt(title="Стоит ли продолжать")
    def season_verdict(show: str) -> str:
        """Вердикт: продолжать смотреть сериал или бросать."""
        return f"""\
Пользователь сомневается, продолжать ли сериал «{show}». Его текущая позиция
есть в ресурсе tracking://watching, профиль вкуса — в tracking://taste.

Возьми профиль сериала одним вызовом show_profile (рейтинги по сезонам)
и сопоставь его с профилем вкуса.

Дай ОДИН вердикт: «продолжай», «перетерпи до N-й серии» или «бросай».

Обоснование — 2–3 строки, обязательно с числами: как менялся рейтинг по сезонам
и как жанр соотносится с тем, что пользователь обычно оценивает высоко.

«Бросай» — допустимый и часто верный ответ. Не подслащивай: доля брошенного
в профиле показывает, что пользователь и сам так делает.
Не пересказывай сюжет непросмотренных серий."""
