"""Ошибки домена.

Слой источника не выпускает наружу `httpx`-исключения: выше по стеку никто не должен
знать, каким клиентом мы ходим в сеть. Каждое сообщение написано так, чтобы его можно
было показать модели без правки — оно объясняет, что ещё доступно, и что делать дальше.
"""

from __future__ import annotations


class TvtrackerError(Exception):
    """Базовая ошибка сервиса."""


class SourceUnavailableError(TvtrackerError):
    """TVmaze не ответил: лимит, таймаут или сеть.

    Сообщение по умолчанию — то самое, что уходит модели: указание на деградацию,
    а не на отказ, потому что локальный поиск и трекинг продолжают работать.
    """

    DEFAULT = (
        "Источник временно ограничил доступ, повтори через ~10 секунд; "
        "локальный поиск и трекинг работают."
    )

    def __init__(self, message: str | None = None) -> None:
        super().__init__(message or self.DEFAULT)


class NotFoundError(TvtrackerError):
    """Запрошенного объекта нет у источника (HTTP 404)."""
